const LABEL = { windows: 'Windows', macos: 'macOS', linux: 'Linux', php: 'PHP', nginx: 'nginx', java: 'Java', apache: 'Apache', openssl: 'OpenSSL', openssh: 'OpenSSH', mysql: 'MySQL / MariaDB', postgresql: 'PostgreSQL', docker: 'Docker', chrome: 'Chrome', firefox: 'Firefox' };
const OS = ['windows', 'macos', 'linux']; // everything else (nginx, Java, ...) is shown under "Software"
let data ={ cves: [] };
let platform = 'all';

const $ = (id) => document.getElementById(id);

function el(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text != null) e.textContent = text;
  return e;
}

function render() {
  const onlyKev = $('only-kev').checked;
  const items = data.cves.filter((c) =>
    (platform === 'all' || c.platforms.some((p) => (OS.includes(p) ? p : 'software') === platform)) &&
    (!onlyKev || c.kev));
  const list = $('list');
  list.textContent = '';
  for (const c of items) {
    const card = el('article', 'cve');
    const head = el('div', 'cve-head');
    const link = el('a', 'cve-id', c.id);
    link.href = 'https://nvd.nist.gov/vuln/detail/' + encodeURIComponent(c.id);
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    head.appendChild(link);
    if (c.kev) head.appendChild(el('span', 'badge badge-kev', 'Exploited'));
    if (c.ransomware) head.appendChild(el('span', 'badge badge-kev', 'Ransomware'));
    if (c.score != null) head.appendChild(el('span', 'badge badge-score', 'CVSS ' + c.score));
    c.platforms.forEach((p) => head.appendChild(el('span', 'badge', (p === 'software' && c.software) || LABEL[p] || p)));
    head.appendChild(el('span', 'cve-date', c.date));
    card.appendChild(head);
    if (c.title) card.appendChild(el('strong', 'cve-title', c.title));
    if (c.product) card.appendChild(el('span', 'cve-product', c.product));
    card.appendChild(el('p', 'cve-desc', c.description || ''));
    if (c.due) card.appendChild(el('span', 'cve-product', 'CISA remediation deadline: ' + c.due));
    list.appendChild(card);
  }
  const updated = data.updated ? ' Last updated: ' + data.updated.replace('T', ' ').replace('Z', ' UTC') + '.' : '';
  $('status').textContent = (items.length ? items.length + ' CVEs.' : 'No CVEs found for this filter.') + updated;
}

document.querySelectorAll('#platforms .tab-btn').forEach((b) => {
  b.addEventListener('click', () => {
    document.querySelectorAll('#platforms .tab-btn').forEach((x) => x.classList.remove('active'));
    b.classList.add('active');
    platform = b.dataset.p;
    render();
  });
});
$('only-kev').addEventListener('change', render);

fetch('../data/cves.json', { cache: 'no-cache' })
  .then((r) => { if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); })
  .then((j) => { data = j; render(); })
  .catch(() => {
    $('status').textContent = 'The CVE list is not available yet. It is generated by the daily job.';
    $('status').classList.add('error');
  });
